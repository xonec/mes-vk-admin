/**
 * 定时任务配置说明：
 * - main: 主函数执行间隔（秒），对应云函数触发器配置，如 5 表示每5秒执行一次（特别注意，阿里云最小间隔是1分钟，即60秒）
 * - tasks: 各子任务配置对象，支持多种格式：
 *
 * 1. 数字（秒数）: timer1: 10  （每10秒执行）
 * 2. 字符串形式:
 *    - '30s' 或 '30秒'   每30秒
 *    - '5m' 或 '5分钟'   每5分钟
 *    - '2h' 或 '2小时'   每2小时
 *    - '00:00:00'       每天0点0分0秒（HH:MM:SS格式）
 *    - '12:30:00'       每天12点30分0秒
 * 3. 对象形式:
 *    - { seconds: 30 }                    每30秒
 *    - { minutes: 5 }                     每5分钟
 *    - { hours: 2 }                       每2小时
 *    - { daily: '00:00:00' }              每天指定时间
 *    - { weekly: [1, 3, 5], time: '09:00:00' }  每周一、三、五 9 点（weekly 可为数字或数组，0=周日，1-6=周一至周六，time 省略默认 00:00:00）
 *    - { monthly: [1, 15], time: '02:00:00' }   每月 1 号、15 号凌晨 2 点（monthly 可为数字或数组，取值 1-31）
 *    - { cron: '0 30 9 * * 1' }           cron 表达式：每周一 9:30
 *    - { seconds: 30, enabled: false }    禁用任务
 *    - { minutes: 5, desc: '描述' }       带描述
 * 4. 数组形式（多时间点执行）:
 *    - ['10s', '1m']                      每10秒和每1分钟都执行
 *    - [10, 60, 300]                      每10秒、1分钟、5分钟都执行
 *    - ['00:00:00', '12:00:00']           每天0点和12点执行
 *    - [{ minutes: 5 }, { hours: 1 }]    每5分钟和每1小时都执行
 *    - { times: ['10s', '1m'], desc: '多时间任务' }  带描述的多时间配置
 * 5. cron 表达式（字符串直写或对象 cron 字段）:
 *    - 字段格式：秒 分 时 日 月 周（6 字段），也支持 5 字段（分 时 日 月 周，秒补 0）和 7 字段（末位为年）
 *    - 通配符：* 任意值；, 列表；- 范围；/ 步长（如 *\/30 表示每 30 个单位）
 *    - 周字段：0-7（0 和 7 均为周日）或 SUN-SAT 英文缩写；「日」和「周」同时指定时为「或」关系
 *    - 示例：'0 0 12 * * 3' 每周三 12 点；'0 *\/30 9-17 * * 1-5' 工作日 9:00-17:30 每半小时
 *    - 此处的 cron 由框架在代码层匹配，不受云厂商触发器限制（如支付宝云触发器不支持周字段，但此处支持）
 *
 * 注意：
 * - 间隔类任务的总秒数必须是 main 的整数倍，否则配置验证失败时不会执行任何任务
 * - daily/weekly/monthly/cron 类任务按 timezone 配置的时区匹配（默认 UTC+8）
 * - 定时点类任务的实际执行时刻按 main 粒度对齐（如 main 为 60 时，cron 秒字段细于 60 秒的多个触发点会合并为一次执行）
 */
